/// The byte budget one retrieval unit is cut to, and the only number in
/// this reader that survives rulings 0398/0401/0403's removal of
/// size-derived refusal.
///
/// It refuses nothing. It is the unitizer's own chunk width — the
/// "65536" every unitizer id here is literally named after
/// (`UNITIZER_ID`, `MULTILINE_UNITIZER_ID`,
/// `DOCUMENT_MARKDOWN_UNITIZER_ID`) — so it is part of what a staged
/// generation recorded and what `AtlasStore::validate_generation`
/// re-derives a unit's identity against, not a decision about whether
/// admitted text may be read. Larger text simply becomes more units.
const MAX_UNIT_BYTES: usize = 64 * 1024;
const UNITIZER_ID: &str = "utf8-line-chunks-65536/v1";
/// Edition v4's unitizer. `utf8-line-chunks-65536/v1` never packed more
/// than one line into a unit despite its own "65536" name — a file with
/// more lines than `MAX_TEXT_UNITS` (e.g. `wirk/src/wirkd/server.rs` at
/// 16,857 lines) hit the unit-count budget while each unit sat far under
/// the byte budget it was named for. This unitizer packs consecutive
/// short lines into one unit up to the same 65536-byte budget — the
/// budget the name always promised — so unit count now tracks bytes, not
/// lines. A line that alone exceeds the budget still splits exactly as
/// `v1` did. See `W4-EXTRACTOR-MULTILINE.md`.
const MULTILINE_UNITIZER_ID: &str = "utf8-multiline-chunks-65536/v1";
/// Edition v5's document unitizer: the same byte-budget chunker
/// `MULTILINE_UNITIZER_ID` names, applied to the Markdown `anydoc` 0.2.4
/// renders from an Office/PDF/CSV file rather than to the file's own
/// bytes. Distinct from `MULTILINE_UNITIZER_ID` on purpose — a reader
/// must be able to tell from this id alone that a unit's offsets index
/// converted Markdown, not the original document
/// (`ContentFamily::Document`'s own doc comment carries the rest).
const DOCUMENT_MARKDOWN_UNITIZER_ID: &str = "anydoc-0.2.4-markdown+utf8-multiline-chunks-65536/v1";

